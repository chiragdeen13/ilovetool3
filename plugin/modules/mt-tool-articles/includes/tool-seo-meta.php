/* ============================================================
   SEO META OUTPUT — now handled by modules/ilt3-seo
   ============================================================

   This function used to run on wp_head and echo a raw <title> element,
   plus description / canonical / OG / Twitter tags.

   The problem: WordPress and the active theme ALREADY print a <title> via
   the standard title-tag theme support. So every tool page was serving two
   <title> elements. Browsers and crawlers keep the first one they meet,
   which meant the hand-written SEO titles in mta_seo_meta() above were
   largely being ignored — and an audit reports it as a duplicate-title
   error on every tool page. The same duplication risk applied to the
   canonical tag, which WordPress core also outputs on singular views.

   None of that copywriting is lost. The mta_seo_meta() table above is still
   the source of truth; ILT3_SEO::curated_meta() reads it and applies the
   title through the correct pre_get_document_title filter, so there is now
   exactly one <title>, one meta description and one canonical per page —
   with the intended text actually winning. The SEO module also adds the
   og:image / twitter:image tags that were missing here entirely, and
   covers the homepage, blog and archives, which this function skipped.

   The hook is only re-registered if the SEO module is absent, so this file
   still works standalone (e.g. if the module folder is ever removed).
   ------------------------------------------------------------ */

add_action('wp_head', 'mta_inject_seo_meta', 5);
function mta_inject_seo_meta() {
    /* The ilt3-seo module owns head meta now. */
    if (class_exists('ILT3_SEO_Meta')) { return; }

    if (is_admin() || !is_singular('page') || is_front_page()) { return; }

    global $post;
    if (!$post) { return; }

    $excluded = array('home','homepage','about','contact','contact-us','privacy-policy','privacy','terms','terms-and-conditions','terms-of-service','blog','news','sample-page','cart','checkout','my-account','shop');
    if (in_array($post->post_name, $excluded, true)) { return; }

    $allMeta = mta_seo_meta();
    $slugKey = strtolower($post->post_name);

    /* exact match ya contains match */
    $meta = isset($allMeta[$slugKey]) ? $allMeta[$slugKey] : null;
    if (!$meta) {
        foreach ($allMeta as $k => $m) {
            if (strlen($k) > 4 && strpos($slugKey, $k) !== false) { $meta = $m; break; }
        }
    }
    if (!$meta && function_exists('mta_find_article')) {
        $art = mta_find_article($slugKey, $post->post_title);
        if (!empty($art['seo'])) { $meta = $art['seo']; }
    }

    $siteName   = get_bloginfo('name');
    $seoTitle   = $meta ? $meta['title'] : $post->post_title . ' - Free Online Tool | ' . $siteName;
    $metaDesc   = $meta ? $meta['meta'] : wp_trim_words(strip_tags(strip_shortcodes($post->post_content)), 28, '...');
    $canonical  = get_permalink($post->ID);

    echo "\n<!-- MT Tool Articles SEO (fallback mode) -->\n";

    /* NOTE: no <title> here on purpose — see the comment above. The theme's
       own title-tag output is the only one, and the fallback filter below
       makes it use the curated title. */
    echo '<meta name="description" content="' . esc_attr($metaDesc) . '" />' . "\n";

    if (!has_action('wp_head', 'rel_canonical')) {
        echo '<link rel="canonical" href="' . esc_url($canonical) . '" />' . "\n";
    }

    /* Open Graph */
    echo '<meta property="og:title" content="' . esc_attr($seoTitle) . '" />' . "\n";
    echo '<meta property="og:description" content="' . esc_attr($metaDesc) . '" />' . "\n";
    echo '<meta property="og:type" content="website" />' . "\n";
    echo '<meta property="og:url" content="' . esc_url($canonical) . '" />' . "\n";
    echo '<meta property="og:site_name" content="' . esc_attr($siteName) . '" />' . "\n";

    /* Twitter */
    echo '<meta name="twitter:card" content="summary" />' . "\n";
    echo '<meta name="twitter:title" content="' . esc_attr($seoTitle) . '" />' . "\n";
    echo '<meta name="twitter:description" content="' . esc_attr($metaDesc) . '" />' . "\n";
}

/* Fallback title filter, used only when the ilt3-seo module is unavailable. */
add_filter('pre_get_document_title', 'mta_fallback_document_title', 20);
function mta_fallback_document_title($title) {
    if (class_exists('ILT3_SEO_Meta')) { return $title; }
    if (is_admin() || is_feed() || !is_singular('page') || is_front_page()) { return $title; }

    global $post;
    if (!$post) { return $title; }

    $excluded = array('home','homepage','about','contact','contact-us','privacy-policy','privacy','terms','terms-and-conditions','terms-of-service','blog','news','sample-page','cart','checkout','my-account','shop');
    if (in_array($post->post_name, $excluded, true)) { return $title; }

    $allMeta = mta_seo_meta();
    $slugKey = strtolower($post->post_name);
    if (isset($allMeta[$slugKey])) { return $allMeta[$slugKey]['title']; }

    foreach ($allMeta as $k => $m) {
        if (strlen($k) > 4 && strpos($slugKey, $k) !== false) { return $m['title']; }
    }

    return $title;
}
